"""
Regenerates the SQL code-table functions in database/02_functions.sql from
src/lib/academic-codes.ts, so the database and the app always use identical codes.

    python scripts/gen-id-code-sql.py          (run after editing academic-codes.ts)
    python scripts/gen-id-code-sql.py --check  (exit 1 if the SQL is out of date — use in CI)
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
ts = (ROOT / 'src/lib/academic-codes.ts').read_text(encoding='utf8')
sql_path = ROOT / 'database/02_functions.sql'
sql = sql_path.read_text(encoding='utf8')

def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"

# PROGRAM_CATALOG
catalog = ts[ts.index('PROGRAM_CATALOG'):ts.index('export const PROGRAMS')]
programs = []
for m in re.finditer(r"name: '([^']+)', code: '([A-Z]{3})',\s*branches: \[(.*?)\]", catalog, re.S):
    branches = re.findall(r"\{ name: '([^']+)', code: '([A-Z]{2})' \}", m.group(3))
    programs.append((m.group(1), m.group(2), branches))
assert len(programs) >= 7, programs

# DEPARTMENT_CODES / EMPLOYEE_TYPE_CODES
def parse_map(name: str):
    block = ts[ts.index(f'export const {name}'):]
    block = block[:block.index('};')]
    # keys are either quoted ('Computer Science') or bare identifiers (CSE, fee_management)
    return re.findall(r"(?:'([^']+)'|\b([A-Za-z_][A-Za-z0-9_]*)):\s*'([A-Z]{2})'", block)

departments = [(a or b, c) for a, b, c in parse_map('DEPARTMENT_CODES')]
emp_types = [(a or b, c) for a, b, c in parse_map('EMPLOYEE_TYPE_CODES')]

program_case = '\n    '.join(f'when {q(n)} then {q(c)}' for n, c, _ in programs)
branch_case = '\n      '.join(
    f'when {q(n)} then case p_branch ' + ' '.join(f'when {q(b)} then {q(bc)}' for b, bc in br) + ' end'
    for n, _, br in programs)
dept_case = '\n    '.join(f'when {q(n)} then {q(c)}' for n, c in departments)
emp_case = ' '.join(f'when {q(n)} then {q(c)}' for n, c in emp_types)

block = f'''-- >>> generated by scripts/gen-id-code-sql.py from src/lib/academic-codes.ts — do not edit by hand
create or replace function public.program_code(p_program text)
returns text
language sql
immutable
as $$
  select coalesce(case p_program
    {program_case}
    end,
    -- unknown program: first 3 letters, never one of the reserved staff categories
    (select case when x in ('TCH', 'EMP', 'ADM') then 'STU' else x end
       from (select rpad(left(upper(regexp_replace(coalesce(p_program, ''), '[^A-Za-z]', '', 'g')), 3), 3, 'X') as x) t));
$$;

create or replace function public.branch_code(p_program text, p_branch text)
returns text
language sql
immutable
as $$
  select coalesce(case p_program
      {branch_case}
    end,
    rpad(left(upper(regexp_replace(coalesce(p_branch, ''), '[^A-Za-z]', '', 'g')), 2), 2, 'X'));
$$;

create or replace function public.department_code(p_department text)
returns text
language sql
immutable
as $$
  select case
    when p_department is null or trim(p_department) = '' then 'GN'
    else coalesce(case p_department
    {dept_case}
    end, rpad(left(upper(regexp_replace(p_department, '[^A-Za-z]', '', 'g')), 2), 2, 'X')) end;
$$;

create or replace function public.employee_type_code(p_type text)
returns text
language sql
immutable
as $$
  select coalesce(case p_type {emp_case} end, 'GN');
$$;
-- <<< generated
'''

start_marker = '-- >>> generated by scripts/gen-id-code-sql.py'
end_marker = '-- <<< generated\n'
if start_marker in sql:
    a = sql.index(start_marker)
    b = sql.index(end_marker, a) + len(end_marker)
    sql = sql[:a] + block + sql[b:]
else:
    a = sql.index('create or replace function public.program_code(p_program text)')
    b = sql.index('create or replace function public.exam_session_code(p_exam_type text)')
    sql = sql[:a] + block + '\n' + sql[b:]
if '--check' in sys.argv:
    if sql != sql_path.read_text(encoding='utf8'):
        print('database/02_functions.sql is out of date: run python scripts/gen-id-code-sql.py')
        sys.exit(1)
    print('ID code tables are in sync')
    sys.exit(0)
sql_path.write_text(sql, encoding='utf8')
print(f'programs={len(programs)} departments={len(departments)} employee_types={len(emp_types)}')
